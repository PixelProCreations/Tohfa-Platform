/**
 * Invoice Detail: the read-only invoice, on GET /invoices/{id} (plan phase 7),
 * with Download.
 *
 * Gate (FINAL_LIST row 4): read-only; Download renders for invoice.view_own.
 * Scope is the server's (BR-36, BR-30): an invoice outside the caller's scope
 * is 404, shown here as "not found" (an empty result, never a 403-style "not
 * allowed", CLAUDE.md 2.1). A host that passes no invoice uuid (a sample
 * invoice number) gets "not found" without a request.
 *
 * Download asks the server for a signed 5-minute link to the PDF
 * (GET /invoices/{id}/download?redirect=true) and opens it in the device's
 * viewer; the PDF is the document of record.
 *
 * Shows exactly what the invoice carries: number, issue date, type, status,
 * place of supply, the lines (description, HSN, quantity x unit price, line
 * total) and the amount summary (taxable value, each non-zero tax component,
 * total), all as the server sent them.
 *
 * Order No. and Customer show only when the host passes the order the invoice
 * was opened from (M5-18, the order invoice): GET /invoices/{id} carries
 * neither, so they come from that order's detail, and only when the invoice
 * names that very order (invoiceOrderContext). Only the buyer's name is
 * shown, never a mobile (BR-92).
 *
 * Hidden, because GET /invoices/{id} has no such field: Bill To (no customer
 * on the invoice; the order invoice adds only the name, as above), Order
 * Number on the billing area's own detail (only the order uuid), Sales Channel, Payment
 * Information, Discount, Warehouse, Generated By, Download Availability and
 * the Invoice Timeline. Share is hidden too: the signed link expires after 5
 * minutes, so there is nothing lasting to share. The old in-app "Invoice
 * Preview" and its "Invoice downloaded" toast are gone: the real PDF opens.
 */
// Design id: M9-S03
import React from 'react';
import { RefreshControl, ScrollView, StyleSheet, Text, View } from 'react-native';

import { t } from '../../../i18n';
import { adminColors, adminSpacing, adminType } from '../../../theme';
import { AdminErrorState, AdminLoadingState } from '../shared/AsyncStates';
import { queryViewState } from '../shared/queryViewState';
import {
  ActionError,
  BillingButton,
  BillingFooter,
  BillingScreen,
  Card,
  DownloadIcon,
  HeaderIconButton,
  InfoCard,
  InfoNote,
  isAllWarehouses,
  PermissionNote,
  SectionTitle,
  ToneBadge,
} from './BillingParts';
import { invoiceOrderContext } from './mappers';
import type { BillingLiveStateProps, InvoiceDetailView, InvoiceOrderRef, WarehouseScreenBaseProps } from './types';

export interface InvoiceDetailScreenProps extends WarehouseScreenBaseProps, Omit<BillingLiveStateProps, 'onLoadMore' | 'hasMore'> {
  /** The id the host asked for (shown in the not-found note). */
  invoiceId: string;
  /** The live invoice (./useBillingData.ts useInvoice); undefined until it loads. */
  invoice?: InvoiceDetailView | undefined;
  /** The order the invoice was opened from (M5-18); omitted on the billing area's own detail. */
  order?: InvoiceOrderRef | undefined;
  /** The host had no invoice uuid to look up. */
  notFound?: boolean | undefined;
  /** Opens the invoice PDF (signed link). */
  onDownload?: ((invoiceId: string) => void) | undefined;
  isDownloading?: boolean | undefined;
  downloadError?: unknown;
}

export function InvoiceDetailScreen({
  scope,
  can,
  onBack,
  invoiceId,
  invoice,
  order,
  notFound = false,
  onDownload,
  isDownloading = false,
  downloadError,
  isLoading = false,
  error,
  onRetry,
  onRefresh,
  isRefreshing = false,
}: InvoiceDetailScreenProps) {
  const canView = can('invoice.view_own');
  const view = notFound ? 'notFound' : invoice !== undefined ? 'ready' : queryViewState({ isLoading, error, itemCount: 0 });

  if (view !== 'ready' || invoice === undefined) {
    return (
      <BillingScreen title={t('billing.detail.title')} onBack={onBack}>
        {view === 'loading' ? (
          <AdminLoadingState />
        ) : view === 'error' ? (
          <AdminErrorState error={error} onRetry={onRetry} />
        ) : (
          <View style={styles.scrollContent}>
            <PermissionNote>{t('billing.detail.notFound', { id: invoiceId })}</PermissionNote>
          </View>
        )}
      </BillingScreen>
    );
  }

  const record = invoice;
  const download = canView && onDownload ? () => onDownload(record.id) : undefined;
  const downloadLabel = t(isDownloading ? 'billing.action.downloading' : 'billing.action.downloadInvoice');

  const orderContext = invoiceOrderContext(record, order);
  const orderRow =
    orderContext === null
      ? []
      : [
          [
            { label: t('billing.detail.orderNumber'), value: orderContext.orderNumber },
            ...(orderContext.customerName !== null ? [{ label: t('billing.detail.customer'), value: orderContext.customerName }] : []),
          ],
        ];
  const infoRows = [
    [
      { label: t('billing.detail.invoiceNumber'), value: record.invoiceNumber },
      { label: t('billing.detail.date'), value: record.issueDateLabel },
    ],
    ...orderRow,
    [
      { label: t('billing.detail.invoiceType'), value: record.typeLabel },
      { label: t('billing.detail.status'), value: record.statusLabel },
    ],
    ...(record.placeOfSupply !== null ? [[{ label: t('billing.detail.placeOfSupply'), value: record.placeOfSupply }]] : []),
  ];

  return (
    <BillingScreen
      title={t('billing.detail.title')}
      subtitle={t('billing.detail.subtitle', { number: record.invoiceNumber, status: record.statusLabel })}
      onBack={onBack}
      headerRight={
        download ? (
          <HeaderIconButton onPress={isDownloading ? () => undefined : download} accessibilityLabel={downloadLabel}>
            <DownloadIcon />
          </HeaderIconButton>
        ) : null
      }
      footer={
        download ? (
          <BillingFooter>
            <ActionError error={downloadError} />
            <BillingButton label={downloadLabel} icon={<DownloadIcon />} onPress={download} disabled={isDownloading} />
          </BillingFooter>
        ) : null
      }
    >
      <ScrollView
        contentContainerStyle={styles.scrollContent}
        showsVerticalScrollIndicator={false}
        refreshControl={
          onRefresh ? (
            <RefreshControl refreshing={isRefreshing} onRefresh={onRefresh} tintColor={adminColors.brand} colors={[adminColors.brand]} />
          ) : undefined
        }
      >
        <View style={styles.brandBlock}>
          <Text style={styles.brandTitle}>{t('billing.detail.brandName')}</Text>
          <Text style={styles.brandSubtitle}>{t('billing.detail.brandTagline')}</Text>
          <View style={styles.brandDivider} />
          <Text style={styles.invoiceDocLabel}>{t('billing.detail.docLabel', { number: record.invoiceNumber })}</Text>
          <View style={styles.badgeRow}>
            <ToneBadge label={record.statusLabel} tone={record.tone} />
          </View>
        </View>

        <SectionTitle>{t('billing.detail.section.info')}</SectionTitle>
        <InfoCard rows={infoRows} />

        <SectionTitle>{t('billing.detail.section.lines')}</SectionTitle>
        <Card>
          {record.lines.length === 0 ? (
            <Text style={styles.itemMeta}>{t('billing.detail.noLines')}</Text>
          ) : (
            record.lines.map((item, index) => (
              <View key={item.key}>
                {index > 0 ? <View style={styles.divider} /> : null}
                <View style={styles.itemRow}>
                  <View style={styles.itemLeft}>
                    <Text style={styles.itemName}>{item.description}</Text>
                    {item.hsnCode !== null ? (
                      <Text style={styles.itemMeta}>{t('billing.detail.hsn', { code: item.hsnCode })}</Text>
                    ) : null}
                    <Text style={styles.itemMeta}>
                      {t('billing.detail.lineQty', { qty: item.qtyLabel, price: item.unitPriceLabel })}
                    </Text>
                  </View>
                  <Text style={styles.itemPrice}>{item.totalLabel}</Text>
                </View>
              </View>
            ))
          )}
        </Card>

        <SectionTitle>{t('billing.detail.section.amount')}</SectionTitle>
        <Card>
          <View style={styles.summaryRow}>
            <Text style={styles.summaryLabel}>{t('billing.detail.taxable')}</Text>
            <Text style={styles.summaryValue}>{record.taxableLabel}</Text>
          </View>
          {record.taxRows.map((row) => (
            <View key={row.key} style={styles.summaryRow}>
              <Text style={styles.summaryLabel}>{row.label}</Text>
              <Text style={styles.summaryValue}>{row.amountLabel}</Text>
            </View>
          ))}
          <View style={styles.divider} />
          <View style={styles.summaryRow}>
            <Text style={styles.totalLabel}>{t('billing.detail.total')}</Text>
            <Text style={styles.totalValue}>{record.totalLabel}</Text>
          </View>
        </Card>

        {isAllWarehouses(scope) ? (
          <>
            <InfoNote>{t('billing.detail.note.farmAnonymous')}</InfoNote>
            {canView ? <InfoNote>{t('billing.detail.note.signedLink')}</InfoNote> : null}
          </>
        ) : null}
      </ScrollView>
    </BillingScreen>
  );
}

const styles = StyleSheet.create({
  scrollContent: { paddingHorizontal: adminSpacing.lg, paddingTop: adminSpacing.md, paddingBottom: adminSpacing.xl },
  brandBlock: { alignItems: 'center', paddingVertical: adminSpacing.md },
  brandTitle: { ...adminType.title, color: adminColors.brand },
  brandSubtitle: { ...adminType.rowMeta, color: adminColors.muted, marginTop: 2, textAlign: 'center' },
  brandDivider: {
    alignSelf: 'stretch',
    height: 1,
    backgroundColor: adminColors.border,
    marginVertical: adminSpacing.sm,
  },
  invoiceDocLabel: { ...adminType.sectionHead, color: adminColors.ink },
  badgeRow: { marginTop: adminSpacing.xs },

  divider: { height: 1, backgroundColor: adminColors.border, marginVertical: adminSpacing.sm },
  itemRow: { flexDirection: 'row', alignItems: 'flex-start', justifyContent: 'space-between' },
  itemLeft: { flex: 1 },
  itemName: { ...adminType.rowTitle, color: adminColors.ink },
  itemMeta: { ...adminType.rowMeta, color: adminColors.muted, marginTop: 1 },
  itemPrice: { ...adminType.sectionHead, color: adminColors.ink },

  summaryRow: {
    flexDirection: 'row',
    justifyContent: 'space-between',
    alignItems: 'center',
    paddingVertical: adminSpacing.xs,
  },
  summaryLabel: { ...adminType.body, color: adminColors.muted },
  summaryValue: { ...adminType.rowTitle, color: adminColors.ink },
  totalLabel: { ...adminType.sectionHead, color: adminColors.ink },
  totalValue: { ...adminType.kpiValue, color: adminColors.ink },
});
