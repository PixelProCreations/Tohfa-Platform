/**
 * Warehouse floor staff roster (docs/openapi.yaml /admin/warehouse-staff, BR-83):
 *   GET  /admin/warehouse-staff                  admin.staff.list_view  (SA/TOHFA all, MAIN own, SUB none)
 *   GET  /admin/warehouse-staff/{id}             admin.staff.list_view  (404 outside scope)
 *   POST /admin/warehouse-staff                  admin.staff.manage     (SA/TOHFA all, MAIN own, SUB none)
 *   PATCH /admin/warehouse-staff/{id}            admin.staff.manage
 *   POST /admin/warehouse-staff/{id}/deactivate  admin.staff.manage     (soft, idempotent)
 *
 * Shapes mirror apps/api/src/modules/warehouse-staff/warehouse-staff.schema.ts.
 * A staff member is NOT a user (no login) and the record has exactly these
 * fields: there is no staff type (driver / warehouse), no email, no vehicle and
 * no delivery figures, so this module carries none of them.
 *
 * The bodies are strict on the server (an unknown field is 422), so only the
 * documented fields are ever sent. No route moves money and none declares an
 * Idempotency-Key: the PATCH is a field update and deactivate is idempotent by
 * itself (BR-83g, BR-83h).
 *
 * No UI imports, so any admin area can reuse it.
 */
import type { ErrorCode, GenericProblemCode } from '@tohfa/shared-types';
import type { Page } from '../../../shell/api/pagination';
import { adminGet, adminPatch, adminPost } from './http';

/** warehouse-staff.schema.ts staffStatuses. */
export const STAFF_STATUSES = ['ACTIVE', 'INACTIVE'] as const;
export type StaffStatus = (typeof STAFF_STATUSES)[number];

/** docs/openapi.yaml `WarehouseStaff`. */
export interface StaffDto {
  id: string;
  /** STF-nnnn, generated by the server. */
  staffCode: string;
  warehouseId: string;
  fullName: string;
  designation: string;
  phone: string | null;
  /** YYYY-MM-DD. */
  joinedOn: string;
  status: StaffStatus;
  createdAt: string;
  updatedAt: string | null;
}

/** docs/openapi.yaml `WarehouseStaffCreate`. */
export interface CreateStaffBody {
  /** 1-120 chars after trim. */
  fullName: string;
  /** 1-80 chars after trim. */
  designation: string;
  /** 10-15 digits, optional leading +. */
  phone?: string;
  /** YYYY-MM-DD. */
  joinedOn: string;
  /** Required for an actor not assigned to a warehouse (Main, Super Admin, Tohfa Admin). */
  warehouseId?: string;
  status?: StaffStatus;
}

/** docs/openapi.yaml `WarehouseStaffUpdate`: at least one field. */
export interface UpdateStaffBody {
  fullName?: string;
  designation?: string;
  /** null clears the phone. */
  phone?: string | null;
  joinedOn?: string;
  status?: StaffStatus;
}

export interface ListStaffParams {
  warehouseId?: string | undefined;
  status?: StaffStatus | undefined;
  /** Case-insensitive match on name or staff code; 1-100 chars. */
  q?: string | undefined;
  cursor?: string | undefined;
  /** 1-100, server default 20. */
  limit?: number | undefined;
}

/** The largest page the server accepts. */
export const STAFF_LIST_MAX_LIMIT = 100;

/** API validation limits (warehouse-staff.schema.ts), not business thresholds. */
export const STAFF_NAME_MAX = 120;
export const STAFF_DESIGNATION_MAX = 80;
export const STAFF_SEARCH_MAX = 100;
/** Must match the CHECK on warehouse_staff.phone. */
export const STAFF_PHONE_PATTERN = /^\+?[0-9]{10,15}$/;

/** Problem codes these routes document (401/403/404/409/422/500). */
export const ERROR_CODES: readonly (GenericProblemCode | ErrorCode)[] = [
  'UNAUTHENTICATED',
  'FORBIDDEN',
  'NOT_FOUND',
  'CONFLICT',
  'VALIDATION_FAILED',
  'INTERNAL',
];

const BASE = '/admin/warehouse-staff';

function staffPath(id: string): string {
  return `${BASE}/${encodeURIComponent(id)}`;
}

/** The roster in name order, cursor paged. A blank search is not sent (the server needs 1+ chars). */
export function listStaff(params: ListStaffParams = {}, signal?: AbortSignal): Promise<Page<StaffDto>> {
  const q = params.q?.trim();
  return adminGet<Page<StaffDto>>(
    BASE,
    {
      warehouseId: params.warehouseId,
      status: params.status,
      q: q === undefined || q === '' ? undefined : q,
      cursor: params.cursor,
      limit: params.limit,
    },
    signal,
  );
}

export function getStaff(id: string, signal?: AbortSignal): Promise<StaffDto> {
  return adminGet<StaffDto>(staffPath(id), undefined, signal);
}

export function createStaff(body: CreateStaffBody): Promise<StaffDto> {
  return adminPost<StaffDto>(BASE, body);
}

export function updateStaff(id: string, body: UpdateStaffBody): Promise<StaffDto> {
  return adminPatch<StaffDto>(staffPath(id), body);
}

/** Soft deactivation; replaying it on an inactive member is a no-op. No body. */
export function deactivateStaff(id: string): Promise<StaffDto> {
  return adminPost<StaffDto>(`${staffPath(id)}/deactivate`, undefined);
}
