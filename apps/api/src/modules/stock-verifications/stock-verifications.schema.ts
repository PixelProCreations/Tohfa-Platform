/**
 * BR-107: physical stock verification (count vs system). Schemas must match docs/openapi.yaml
 * (/admin/stock-verifications).
 *
 * Request bodies and the list query are `.strict()`. Quantities are decimal STRINGS
 * (numeric(12,3)), never JSON numbers.
 */
import { z } from 'zod';
import { stockAdjustmentResponse, ADJUSTMENT_STATUSES } from '../stock-adjustments/stock-adjustments.schema.js';

/** Matches the CHECK on `stock_verifications.status` (0005). DISPUTED is never written by this API yet. */
export const VERIFICATION_STATUSES = ['RECORDED', 'RECONCILED', 'DISPUTED'] as const;
export type VerificationStatus = (typeof VERIFICATION_STATUSES)[number];

const KG_PATTERN = /^\d{1,9}(\.\d{1,3})?$/;

export const verificationIdParams = z.object({ id: z.string().uuid('verification id must be a UUID') }).strict();
export type VerificationIdParams = z.infer<typeof verificationIdParams>;

/** POST /v1/admin/stock-verifications */
export const createVerificationBody = z
  .object({
    batchId: z.string().uuid(),
    /** What was physically counted; zero allowed (the shelf was empty). */
    countedQtyKg: z
      .string()
      .regex(KG_PATTERN, 'countedQtyKg must be a decimal string with at most 9 integer digits and 3 decimals'),
    notes: z.string().trim().min(1).max(1000).optional(),
  })
  .strict();
export type CreateVerificationBody = z.infer<typeof createVerificationBody>;

/** POST /v1/admin/stock-verifications/:id/adjustment */
export const raiseAdjustmentBody = z
  .object({
    /** Optional; a default naming the count is used when absent. */
    reason: z.string().trim().min(5).max(500).optional(),
  })
  .strict();
export type RaiseAdjustmentBody = z.infer<typeof raiseAdjustmentBody>;

/** GET /v1/admin/stock-verifications */
export const listVerificationsQuery = z
  .object({
    status: z.enum(VERIFICATION_STATUSES).optional(),
    warehouseId: z.string().uuid().optional(),
    batchId: z.string().uuid().optional(),
    hasVariance: z
      .enum(['true', 'false'])
      .transform((value) => value === 'true')
      .optional(),
    page: z.coerce.number().int().min(1).default(1),
    pageSize: z.coerce.number().int().min(1).max(100).default(20),
  })
  .strict();
export type ListVerificationsQuery = z.infer<typeof listVerificationsQuery>;

/** Wire representation of one verification (list, detail, create). */
export const stockVerificationResponse = z.object({
  id: z.string().uuid(),
  warehouseId: z.string().uuid(),
  batchId: z.string().uuid(),
  batchCode: z.string(),
  cropId: z.string().uuid(),
  grade: z.string(),
  /** The ledger balance snapshotted when the count was recorded. */
  systemQtyKg: z.string(),
  countedQtyKg: z.string(),
  /** counted - system, signed (negative = stock missing). Generated by the database. */
  varianceKg: z.string(),
  status: z.enum(VERIFICATION_STATUSES),
  notes: z.string().nullable(),
  verifiedBy: z.string().uuid(),
  verifiedAt: z.string(),
  adjustmentId: z.string().uuid().nullable(),
  adjustmentStatus: z.enum(ADJUSTMENT_STATUSES).nullable(),
  createdAt: z.string(),
  updatedAt: z.string().nullable(),
});
export type StockVerification = z.infer<typeof stockVerificationResponse>;

export const listVerificationsResponse = z.object({
  items: z.array(stockVerificationResponse),
  page: z.number().int(),
  pageSize: z.number().int(),
  total: z.number().int(),
});
export type ListVerificationsResponse = z.infer<typeof listVerificationsResponse>;

/** POST /v1/admin/stock-verifications/:id/adjustment */
export const raisedAdjustmentResponse = z.object({
  verification: stockVerificationResponse,
  adjustment: stockAdjustmentResponse,
});
export type RaisedAdjustment = z.infer<typeof raisedAdjustmentResponse>;
